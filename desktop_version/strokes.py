import numpy as np
from PIL import Image, ImageDraw

def ell(cx, cy, rx, ry, a0=0, a1=360, n=18):
    t = np.deg2rad(np.linspace(a0, a1, n)); return [(cx + rx * np.cos(x), cy + ry * np.sin(x)) for x in t]

