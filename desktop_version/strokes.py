def smooth(p):
    for _ in range(2):
        q = [p[0]]
        for a, b in zip(p, p[1:]): q += [(.75 * a[0] + .25 * b[0], .75 * a[1] + .25 * b[1]), (.25 * a[0] + .75 * b[0], .25 * a[1] + .75 * b[1])]
        p = q + [p[-1]]
    return p

def draw_digit(d, rng):
    ang = rng.uniform(-.25, .25); sh = rng.uniform(-.3, .3); sx = rng.uniform(.65, 1.1); sy = rng.uniform(.8, 1.1)
    M = np.array([[np.cos(ang), -np.sin(ang) + sh], [np.sin(ang), np.cos(ang)]]) @ np.diag([sx, sy])
    ext = rng.uniform(120, 220); w = rng.uniform(12, 30)
    img = Image.new("L", (280, 280), 0); dr = ImageDraw.Draw(img)
    for stroke in SK[d][rng.integers(len(SK[d]))]:
        pts = np.array(smooth(stroke)) - .5 + rng.normal(0, .015, (len(smooth(stroke)), 2))
        pts = (pts @ M.T) * ext + 140 + rng.uniform(-30, 30, 2)
        pts = [tuple(p) for p in pts]; dr.line(pts, fill=255, width=int(w), joint="curve")
        for x, y in (pts[0], pts[-1]): dr.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=255)
    return np.asarray(img, dtype=np.float64) / 255
